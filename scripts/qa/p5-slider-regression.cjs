const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createRequire } = require('node:module');
const auditRoot = process.env.P5_AUDIT_ROOT || path.resolve(__dirname, '../../..');
if (!process.env.P5_TEST_RUNTIME) throw new Error('Set P5_TEST_RUNTIME to a folder containing the test runtime package.json.');
const runtimeRequire = createRequire(path.join(process.env.P5_TEST_RUNTIME, 'package.json'));
const React = runtimeRequire('react');
const renderer = runtimeRequire('react-test-renderer');
const ts = require('typescript');
const roots = ['boise-remodeling-co', 'Boise-Construction-Co', 'Boise-Handyman-Co', 'Boise-Cabinet-Co'];
for (const repo of roots) {
  const source = fs.readFileSync(path.join(auditRoot, repo, 'components/BeforeAfterSlider.tsx'), 'utf8');
  const code = ts.transpileModule(source, {compilerOptions: {jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020}}).outputText;
  const mod = {exports: {}};
  const req = (name) => {
    if (name === 'react') return React;
    if (name === 'react/jsx-runtime') return runtimeRequire('react/jsx-runtime');
    if (name === 'next/image') return {__esModule:true, default:(props) => React.createElement('img', props)};
    if (name === 'lucide-react') return {MoveHorizontal:() => React.createElement('svg')};
    throw new Error(name);
  };
  vm.runInNewContext('(function(require,module,exports){' + code + '\n})')(req,mod,mod.exports);
  const captures = new Set();
  const node = {getBoundingClientRect:()=>({left:0,width:400}),setPointerCapture:id=>captures.add(id),hasPointerCapture:id=>captures.has(id),releasePointerCapture:id=>captures.delete(id)};
  let tree;
  renderer.act(()=> { tree = renderer.create(React.createElement(mod.exports.BeforeAfterSlider,{beforeSrc:'/before.webp',afterSrc:'/after.webp',beforeAlt:'Original kitchen',afterAlt:'Finished kitchen'}),{createNodeMock:()=>node}); });
  const root = () => tree.root.findByProps({'data-testid':'slider-before-after'});
  const handle = () => tree.root.findByProps({'data-testid':'handle-before-after'});
  const value = () => handle().props['aria-valuenow'];
  const event = (extra={}) => ({isPrimary:true,button:0,pointerId:1,pointerType:'mouse',clientX:200,clientY:100,currentTarget:node,...extra});
  const fire = (name,extra) => renderer.act(()=>root().props[name](event(extra)));
  assert.match(root().props.className,/touch-pan-y/);
  assert.equal(value(),50);
  fire('onPointerDown',{clientX:80}); assert.equal(value(),20);
  fire('onPointerMove',{clientX:800}); assert.equal(value(),100);
  assert.match(handle().props.style.left,/clamp\(28px/);
  fire('onPointerUp',{clientX:800}); assert.equal(captures.size,0);
  fire('onPointerMove',{clientX:0}); assert.equal(value(),100);
  fire('onPointerDown',{pointerType:'touch',clientX:200});
  fire('onPointerMove',{pointerType:'touch',clientX:202,clientY:160});
  fire('onPointerUp',{pointerType:'touch',clientX:202,clientY:180});
  assert.equal(value(),100,'Vertical scrolling must preserve the comparison');
  fire('onPointerDown',{pointerType:'touch',clientX:100});
  fire('onPointerMove',{pointerType:'touch',clientX:300}); assert.equal(value(),75);
  fire('onPointerMove',{pointerType:'touch',pointerId:2,isPrimary:false,clientX:0}); assert.equal(value(),75);
  fire('onPointerCancel',{pointerType:'touch'}); assert.equal(captures.size,0);
  fire('onPointerDown',{pointerType:'touch',clientX:60});
  fire('onPointerUp',{pointerType:'touch',clientX:60}); assert.equal(value(),15);
  fire('onPointerDown',{button:2,clientX:0}); assert.equal(value(),15);
  const key = (k,shiftKey=false) => renderer.act(()=>handle().props.onKeyDown({key:k,shiftKey,preventDefault(){}}));
  key('Home'); assert.equal(value(),0);
  key('ArrowRight'); assert.equal(value(),2);
  key('ArrowRight',true); assert.equal(value(),12);
  key('End'); assert.equal(value(),100);
  key('ArrowRight'); assert.equal(value(),100);
  key('ArrowLeft'); assert.equal(value(),98);
  assert.equal(handle().props['aria-valuetext'],'98% before image, 2% after image');
  const imageLayer = tree.root.findByProps({'data-testid':'before-image-layer'});
  assert.equal(imageLayer.props.style.clipPath,'inset(0 2% 0 0)');
  renderer.act(()=>tree.unmount());
  console.log(repo + ': PASS (mouse, touch intent, tap, cancellation, second pointer, keyboard, endpoints, reveal state)');
}
